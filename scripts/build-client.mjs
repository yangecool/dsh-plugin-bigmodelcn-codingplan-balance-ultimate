/**
 * Bundle `src/client/entry.js` into the single classic script the Harness
 * Client module loader executes: `lib/client.js`.
 *
 * The bundle is an IIFE that registers one lazy factory through
 * `window.__ModuleLoader__.load`; React arrives later through the factory's
 * `require('react')`. The artifact is committed because installed profiles run
 * it directly and never build this package.
 */
import { build } from 'esbuild';
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outfile = `${root}lib/client.js`;
const packageJson = JSON.parse(readFileSync(`${root}package.json`, 'utf8'));

await build({
  absWorkingDir: root,
  entryPoints: ['src/client/entry.js'],
  outfile,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  charset: 'utf8',
  minify: false,
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: `// ${packageJson.name} v${packageJson.version} — generated by scripts/build-client.mjs. Do not edit.`,
  },
});

const body = readFileSync(outfile, 'utf8');
for (const required of ['__ModuleLoader__', packageJson.name]) {
  if (!body.includes(required)) {
    throw new Error(`build-client: output is missing ${JSON.stringify(required)}`);
  }
}
if (/^\s*(import|export)\s/m.test(body)) {
  throw new Error('build-client: output still contains ESM statements');
}
writeFileSync(outfile, body, 'utf8');
const kib = (statSync(outfile).size / 1024).toFixed(1);
console.log(`built lib/client.js (${kib} KiB)`);
